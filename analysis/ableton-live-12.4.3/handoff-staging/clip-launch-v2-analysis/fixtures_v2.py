"""Fixture bases and edits for the clip-launch-v2 candidate (analyst side; never shipped).

Every fixture starts from the minimal Live Set T11-MIN, generated by
r2/t11-structure-v1/make_fixture.py (imported read-only; no shipped bytes), with its two device
items removed (the device list is V in SPEC-LIVE-SET-STRUCTURE's minimal-set table; removing them
drops the A6 dependency of that spec). Older format versions are T11-MIN in that version's schema
form:
  12.0_12117  elements the 12.0_12117 schema does not declare are removed;
  11.0_405    MainTrack -> MasterTrack, Scenes -> SceneNames (scenes keep only Id and the name as
              attribute Value), Color -> ColorIndex where the class declares ColorIndex, both clips
              in the old clip form (five follow fields after VelocityAmount, values OLD_T), then
              every element the 11.0_405 schema does not declare is removed.
The renames reverse conversion steps the clip-launch-v1 reviewer read (review/other-steps.c:
ColorIndex -> Color, SceneNames -> Scenes (step 414), MasterTrack -> MainTrack). Removing an
undeclared element changes nothing that is read: the reader skips undeclared children
(REQ-LIVE-SET-STRUCTURE-001), so removal only avoids relying on that rule.
Interface: base(version) -> ET root; apply(root, edits); render(root) -> str; diff(a, b) -> [str].
"""
