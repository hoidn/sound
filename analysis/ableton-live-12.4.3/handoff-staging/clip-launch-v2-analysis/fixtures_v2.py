import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
T11 = REPO / "analysis/ableton-live-12.4.3/r2/t11-structure-v1"
SCHEMA_DIR = Path("/home/ollie/Ableton Live 12 Suite.app/Contents/App-Resources/Schema")
V12402, V12117, V405 = "12.0_12402", "12.0_12117", "11.0_405"

SC = "Tracks/MidiTrack[1]/DeviceChain/MainSequencer/ClipSlotList/ClipSlot[1]/ClipSlot/Value/MidiClip"
SA = "Tracks/AudioTrack[1]/DeviceChain/MainSequencer/ClipSlotList/ClipSlot[1]/ClipSlot/Value/AudioClip"
AR = "Tracks/MidiTrack[1]/DeviceChain/MainSequencer/ClipTimeable/ArrangerAutomation/Events/MidiClip[1]"
SN = "Scenes/Scene[1]"
OLD_T = [("FollowTime", "4"), ("FollowActionA", "0"), ("FollowActionB", "0"), ("FollowChanceA", "1"),
         ("FollowChanceB", "0")]


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


sys.dont_write_bytecode = True
MF = _load("make_fixture", T11 / "make_fixture.py")
SCK = _load("schema_check", T11 / "schema_check.py")
FAU = _load("fixture_audit", T11 / "fixture_audit.py")
_SCHEMAS = {}
FORM_NOTES = {}  # version -> list of changes from T11-MIN made by base(version)


def schema(version):
    if version not in _SCHEMAS:
        _SCHEMAS[version] = SCK.load_schema(SCHEMA_DIR / f"{version}.txt")
    return _SCHEMAS[version]


def to_et(node):
    tag, attrs, kids = node
    e = ET.Element(tag, dict(attrs))
    e.extend(to_et(k) for k in kids)
    return e


def to_tuple(e):
    return (e.tag, dict(e.attrib), [to_tuple(c) for c in e])


def render(root):
    lines = ['<?xml version="1.0" encoding="UTF-8"?>']
    MF.render(to_tuple(root), 0, lines)
    return "\n".join(lines) + "\n"


def wav_bytes(path=None):
    """The T11-MIN sample: written to path (with its modification time) when given."""
    if path is None:
        return (T11 / "fixtures/Samples/T11-tone.wav").read_bytes()
    return MF.wav(str(path))


def t11_min():
    return to_et(MF.build(wav_bytes()))


def walk(root, sch):
    """Yield (element, schema class) for every compound or list item below LiveSet, as schema_check walks."""
    stack = [(root.find("LiveSet"), "LiveSet")]
    while stack:
        e, cls = stack.pop()
        fields = sch.get(cls)
        if fields is None:
            continue
        yield e, cls
        for c in e:
            f = fields.get(c.tag)
            if f is None:
                continue
            if f[1] == "0":
                stack.append((c, f[0]))
            elif f[1] == "-1":
                stack.extend((item, item.tag) for item in c)


def conform(root, sch):
    """Remove children the schema does not declare for their parent's class; return 'Class/child' names."""
    removed = []
    for e, cls in list(walk(root, sch)):
        for c in list(e):
            if c.tag not in sch[cls]:
                e.remove(c)
                removed.append(f"{cls}/{c.tag}")
    return sorted(set(removed))


def leaf(name, text):
    return ET.Element(name, {"Value": text})


def old_clip_form(clip):
    fa = clip.find("FollowAction")
    i = list(clip).index(fa)
    clip.remove(fa)
    for k, (n, t) in enumerate(OLD_T):
        clip.insert(i + k, leaf(n, t))


def base(version=V12402):
    """T11-MIN without devices, in the given version's form. Returns the root element."""
    root = t11_min()
    ls = root.find("LiveSet")
    notes = ["devices removed: " + ", ".join(f"{t.tag} {d.tag}" for t in ls.find("Tracks")
                                           for d in t.iterfind("DeviceChain/DeviceChain/Devices/*"))]
    for devices in ls.iterfind("Tracks/*/DeviceChain/DeviceChain/Devices"):
        for d in list(devices):
            devices.remove(d)
    if version == V12117:
        root.set("MinorVersion", V12117)
        notes.append("MinorVersion 12.0_12117")
        notes.append("undeclared in 12.0_12117, removed: " + ", ".join(conform(root, schema(V12117))))
    elif version == V405:
        root.set("MinorVersion", V405)
        ls.find("MainTrack").tag = "MasterTrack"
        scenes = ls.find("Scenes")
        scenes.tag = "SceneNames"
        for s in scenes:
            sid, name = s.get("Id"), s.find("Name").get("Value")
            s.clear()
            s.attrib.update({"Id": sid, "Value": name})
        sch = schema(V405)
        for e, cls in walk(root, sch):
            c = e.find("Color")
            if c is not None and "Color" not in sch[cls] and "ColorIndex" in sch[cls]:
                c.tag = "ColorIndex"
        for p in (SC, SA):
            old_clip_form(ls.find(p))
        notes += ["MinorVersion 11.0_405", "MainTrack renamed MasterTrack", "Scenes renamed SceneNames; each Scene "
                  "keeps its Id and its name as attribute Value", "track and clip Color renamed ColorIndex",
                  "MIDI and audio clip follow action in the old clip form: " + ", ".join(f"{n} {t}" for n, t in OLD_T),
                  "undeclared in 11.0_405, removed: " + ", ".join(conform(root, sch))]
    FORM_NOTES[version] = notes
    return root


def arrangement_clip(root, values):
    """Add an arrangement MIDI clip (T11-MIN's MIDI clip form) to the MIDI track's main sequencer."""
    ms = root.find("LiveSet/Tracks/MidiTrack[1]/DeviceChain/MainSequencer")
    clip = to_et(MF.midi_clip())
    for n, t in values.items():
        clip.find(n).set("Value", t)
    ct = ET.Element("ClipTimeable")
    ET.SubElement(ET.SubElement(ct, "ArrangerAutomation"), "Events").append(clip)
    ms.insert(list(ms).index(ms.find("ClipSlotList")) + 1, ct)


def apply(root, edits):
    """edits: list of (op, path, arg). Paths are relative to /Ableton/LiveSet ('' is LiveSet itself).
    set {name: text} on children of path; drop [names] from path; dup (name, text) after the first
    such child; remove the element at path; arr {name: text}: add the arrangement clip."""
    ls = root.find("LiveSet")
    for op, path, arg in edits:
        el = None if op == "arr" else ls if path == "" else ls.find(path)
        if op == "arr":
            arrangement_clip(root, arg)
        elif el is None:
            raise KeyError(f"{op}: no element at {path}")
        elif op == "set":
            for n, t in arg.items():
                el.find(n).set("Value", t)
        elif op == "drop":
            for n in arg:
                el.remove(el.find(n))
        elif op == "dup":
            first = el.find(arg[0])
            el.insert(list(el).index(first) + 1, leaf(*arg))
        elif op == "remove":
            parent = ls.find(path.rsplit("/", 1)[0]) if "/" in path else ls
            parent.remove(el)
        else:
            raise ValueError(op)
    return root


def build_fixture(version, edits):
    return apply(base(version), edits)


def diff(a, b, path=""):
    """Human-readable differences from tree a to tree b (attributes, removed and added children)."""
    out = []
    if a.attrib != b.attrib:
        for k in sorted(set(a.attrib) | set(b.attrib)):
            if a.get(k) != b.get(k):
                out.append(f"{path or '/'} @{k}: {a.get(k)!r} -> {b.get(k)!r}")
    ka, kb = list(a), list(b)
    sm = difflib.SequenceMatcher(a=[c.tag for c in ka], b=[c.tag for c in kb], autojunk=False)
    for op, i1, i2, j1, j2 in sm.get_opcodes():
        if op == "equal":
            for x, y in zip(ka[i1:i2], kb[j1:j2]):
                out += diff(x, y, f"{path}/{x.tag}")
        else:
            out += [f"{path}/{c.tag}: removed" for c in ka[i1:i2]]
            out += [f"{path}/{c.tag}: added ({sum(1 for _ in c.iter())} elements)" for c in kb[j1:j2]]
    return out


def measure(root):
    """Structure-rule measurement (fixture_audit rules) after the renames a conversion makes."""
    version = root.get("MinorVersion")
    m = copy.deepcopy(root)
    dev, pels = SCK.check(schema(version), m)
    ls = m.find("LiveSet")
    for old, new in (("MasterTrack", "MainTrack"), ("SceneNames", "Scenes")):
        if ls.find(old) is not None:
            ls.find(old).tag = new
    r = SCK.rules(m, pels)
    r["negative_list_ids"] = sum(1 for p in m.iter() for c in p if "Id" in c.attrib and c not in pels
                                 and c.get("Id").lstrip().startswith("-"))
    return dev, r, FAU.refusals(r, dev), FAU.unknowns(r)


