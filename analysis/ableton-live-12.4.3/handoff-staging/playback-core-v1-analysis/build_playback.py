"""Build the playback-core-v1 handoff candidate: fixtures, cases.json and the draft manifest (analyst side).

Usage: python3 -I -B build_playback.py build        (writes ../playback-core-v1/fixtures/, cases.json, manifest.json)
       python3 -I -B seal_playback.py               (checks, inventory hashes, author-validation.json, traceability)
Fixtures are Live Sets built on T11-MIN with the helpers and rules of r2/t11-structure-v1/make_fixture.py (imported,
unchanged): one MIDI or audio track, one scene, no devices and no return track. Every value, name and Id is
invented; the two WAVs are generated by integer arithmetic. No shipped file is read. Expected results come from
model_playback.py; spec.md, README.md and AGENTS.md are written by hand. Deterministic: same bytes on every run.
"""
