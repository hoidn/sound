GZ_HEADER = bytes.fromhex("1f8b0800000000000213")  # FLG 0, MTIME 0, XFL 2, OS 19 (als-container-v1 fixture form)
LASTMOD = 1760000000


# ---- generated samples ----
def frames(n, period, seed):
    out, s = [], seed
    for i in range(n):
        s = (s * 1103515245 + 12345) % 2 ** 31
        saw = (i % period) * 24000 // period - 12000
        out.append(max(-32768, min(32767, saw + (s >> 16) % 4001 - 2000)))
    return out


WAVS = {"tone48.wav": (48000, frames(480, 96, 7)), "tone44.wav": (44100, frames(441, 90, 11))}


def write_wav(name):
    rate, fr = WAVS[name]
    path = FIX / "Samples" / name
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(b"".join(struct.pack("<h", x) for x in fr))
    os.utime(path, (LASTMOD, LASTMOD))
    return path.read_bytes()


# ---- Live Set documents (T11-MIN rules) ----
def clip_common(name, color, ls, le, start_rel, loop_on, launch_q, sig):
    return [v("CurrentStart", ls), v("CurrentEnd", le),
            el("Loop", None, v("LoopStart", ls), v("LoopEnd", le), v("StartRelative", start_rel),
               v("LoopOn", "true" if loop_on else "false"), v("OutMarker", le), v("HiddenLoopStart", ls),
               v("HiddenLoopEnd", le)),
            v("Name", name), v("Color", color), v("LaunchMode", 0), v("LaunchQuantisation", launch_q),
            el("TimeSignature", None, el("TimeSignatures", None, el("RemoteableTimeSignature", {"Id": "0"},
               v("Numerator", sig[0]), v("Denominator", sig[1]), v("Time", 0)))),
            el("Envelopes", None, el("Envelopes")), v("Legato", "false"),
            el("GrooveSettings", None, v("GrooveId", -1)), v("VelocityAmount", 0), t11.follow_action()]


def midi_clip(c):
    events = [el("MidiNoteEvent", {"Time": n["time"], "Duration": n["dur"], "Velocity": n["vel_text"],
                                   "VelocityDeviation": "0", "OffVelocity": n["off_text"], "Probability": "1",
                                   "IsEnabled": "true" if n["on"] else "false", "NoteId": str(i + 1)})
              for i, n in enumerate(c["notes"])]
    notes = el("Notes", None,
               el("KeyTracks", None, el("KeyTrack", {"Id": "0"}, el("Notes", None, *events), v("MidiKey", KEY))),
               el("PerNoteEventStore", None, el("EventLists")), el("NoteProbabilityGroups"),
               el("ProbabilityGroupIdGenerator", None, v("NextId", 1)),
               el("NoteIdGenerator", None, v("NextId", len(events) + 1)))
    kids = clip_common(c["name"], 15, c["ls"], c["le"], c["sr"], c["loop_on"], c["q"], c["sig"])
    return el("MidiClip", {"Id": "0", "Time": "0"}, *kids, v("IsWarped", "true"), notes)


def audio_clip(c, wav):
    rate, fr = WAVS[c["wav"]]
    fileref = el("FileRef", None, v("RelativePathType", 1), v("RelativePath", f"Samples/{c['wav']}"),
                 v("Path", f"/playback-core-v1/fixtures/Samples/{c['wav']}"), v("Type", 2), v("LivePackName", ""),
                 v("LivePackId", ""), v("OriginalFileSize", len(wav)), v("OriginalCrc", t11.crc16(wav[:16384])),
                 v("SourceHint", ""))
    sref = el("SampleRef", None, fileref, v("LastModDate", LASTMOD), v("DefaultDuration", len(fr)),
              v("DefaultSampleRate", rate))
    kids = clip_common(c["name"], 3, c["ls"], c["le"], 0, False, c["q"], (4, 4))
    return el("AudioClip", {"Id": "0", "Time": "0"}, *kids, v("IsWarped", "false"), sref, v("WarpMode", 0),
              v("HiQ", "true" if c["hiq"] else "false"), v("Fade", "false"), v("PitchCoarse", c["coarse"]),
              v("PitchFine", 0), v("SampleVolume", c["volume"]),
              el("WarpMarkers", None, el("WarpMarker", {"Id": "0", "SecTime": "0", "BeatTime": "0"}),
                 el("WarpMarker", {"Id": "1", "SecTime": "0.015625", "BeatTime": "0.03125"})))


def set_manual(mixer, tag, value):
    for kid in mixer[2]:
        if kid[0] == tag:
            for k in kid[2]:
                if k[0] == "Manual":
                    k[1]["Value"] = str(value)
                    return
    raise KeyError(tag)


def live_set(s):
    """s: tempo (text), sig (code), gq (GlobalQuantisation), loop (on, start text, length text), track (kind, clip)."""
    ids = t11.Ids()
    kind, clip = s["track"]
    mix, _ = t11.mixer(ids, [])
    tag, eff = ("MidiTrack", "1-MIDI") if kind == "midi" else ("AudioTrack", "1-Audio")
    track = t11.track(tag, 1, "", eff, 15 if kind == "midi" else 3, mix, [],
                      el("MainSequencer", None, t11.slots(clip, 1)), [], 1)
    main_mix, main_t = t11.mixer(ids, [], main=True)
    set_manual(main_mix, "Tempo", s["tempo"])
    set_manual(main_mix, "TimeSignature", s["sig"])
    pre_mix, _ = t11.mixer(ids, [])
    main = el("MainTrack", None, t11.name("", "Main"), v("Color", 69),
              el("AutomationEnvelopes", None, el("Envelopes", None,
                 t11.envelope(0, main_t["TimeSignature"], [el("EnumEvent", {"Id": "0", "Time": t11.L, "Value": str(s["sig"])})]),
                 t11.envelope(1, main_t["Tempo"], [el("FloatEvent", {"Id": "0", "Time": t11.L, "Value": s["tempo"]})]))),
              el("DeviceChain", None, t11.routing("AudioOutputRouting", "AudioOut/External/S0"), main_mix,
                 el("DeviceChain", None, el("Devices"))))
    scene = el("Scene", {"Id": "0"}, t11.follow_action(), v("Name", ""), v("Color", -1), v("Tempo", 120),
               v("IsTempoEnabled", "false"), v("TimeSignatureId", 201), v("IsTimeSignatureEnabled", "false"))
    on, start, length = s.get("loop", (False, "0", "8"))
    liveset = el("LiveSet", None, v("NextPointeeId", ids.n + 1), el("Tracks", None, track), main,
                 el("PreHearTrack", None, el("DeviceChain", None, pre_mix)), el("SendsPre"), el("Scenes", None, scene),
                 el("Transport", None, v("LoopOn", "true" if on else "false"), v("LoopStart", start),
                    v("LoopLength", length), v("LoopIsSongStart", "false"), v("CurrentTime", 0)),
                 v("GlobalQuantisation", s["gq"]), v("AutoQuantisation", 0), v("CrossfadeCurve", 2))
    root = el("Ableton", {"MajorVersion": "5", "MinorVersion": "12.0_12402", "SchemaChangeCount": "1"}, liveset)
    lines = ['<?xml version="1.0" encoding="UTF-8"?>']
    t11.render(root, 0, lines)
    return ("\n".join(lines) + "\n").encode("utf-8")


def gz(data):
    c = zlib.compressobj(9, zlib.DEFLATED, -15)
    body = c.compress(data) + c.flush()
    return GZ_HEADER + body + struct.pack("<II", zlib.crc32(data) & 0xFFFFFFFF, len(data) & 0xFFFFFFFF)


# ---- expectations ----
SIGS = {201: (4, 4), 200: (3, 4), 202: (5, 4), 302: (6, 8), 303: (7, 8)}
GAIN = {"1": 1.0, "0.5011872336272722": 0.5011872053146362, "0": 0.0003162277571391314, "10": 9.999999046325684,
        "20": 15.848933219909668}  # value used by playback for each SampleVolume text (X: audio/results/gain.json)


def clock_for(s, sr, script):
    play = next((a for a in script if a["action"] == "play"), None)
    stop = next((a["at"] for a in script if a["action"] == "stop"), None)
    cont = next((a["at"] for a in script if a["action"] == "continue"), None)
    on, start, length = s.get("loop", (False, "0", "8"))
    return m.Clock(sr, float(s["tempo"]), play["start_beat"] if play else 0.0, stop, cont,
                   (float(start), float(length)) if on else None)


def launch_of(s, clip, clock, script):
    a = next(a for a in script if a["action"] == "launch")
    g = m.grid(s["gq"], SIGS[s["sig"]], clip["q"], clip["sig"])
    if a.get("transport") == "stopped":
        return {"grid": g, "press_beat": a["start_beat"], "B": m.boundary(a["start_beat"], g), "seg": 0}
    t = m.L(clock.beat_at(a["at"]))
    B, seg = m.boundary(t, g), clock.seg_at(a["at"])
    end = clock.segs[seg]["end"]
    assert end is None or m.lat(B) < m.lat(end), "launch boundary at or after the song-loop end"
    return {"grid": g, "press_beat": t, "B": B, "seg": seg}


def midi_expect(s, sr, script, window_end):
    clip = s["track"][1]
    clock = clock_for(s, sr, script)
    ln = launch_of(s, clip, clock, script)
    until = ln["B"] + window_end * clock.bps + 1
    evs = m.note_events(clip["notes"], ln["B"], clip["ls"], clip["le"], clip["sr"], clip["loop_on"], until)
    out, last = [], -1
    for beat, _, kind, key, vel in evs:
        smp = clock.place_clip_beat(beat, ln["seg"])
        if min(smp) >= window_end:
            continue
        assert max(smp) < window_end, ("event straddles the window end", smp)
        assert min(smp) >= last, "events out of sample order"
        last = max(smp)
        out.append({"samples": smp, "type": kind, "key": key, "velocity": vel})
    info = {"samples_per_beat": clock.spb, "press_beat": ln["press_beat"], "grid_beats": ln["grid"],
            "launch_boundary_beat": ln["B"]}
    if clock.loop:
        info["song_loop_jump_samples"] = [j for j in clock.jumps() if j < window_end]
    if script[0]["action"] == "play" and any(a["action"] == "stop" for a in script):
        info["beat_held_at_stop"] = clock.held
    return {"outcome": "opens", "midi": {"track": 1, "window": [0, window_end], "events": out}}, info


def ulp32(x):
    return float(abs(m.np.spacing(m.np.float32(x))))


def audio_expect(s, sr, script):
    clip = s["track"][1]
    clock = clock_for(s, sr, script)
    ln = launch_of(s, clip, clock, script)
    start = clock.place(ln["B"], 0, 0.0)
    assert len(start) == 1
    start = start[0]
    rate, fr = WAVS[clip["wav"]]
    f0 = m.first_frame(rate, float(clip["ls"]))
    inc = m.read_step_fixed(rate, sr, float(clip["coarse"]))
    vals = m.render_clip(fr, f0, inc, 4 * len(fr), GAIN[clip["volume"]])
    direct = inc == 1 << 32
    if direct:
        tol = {"kind": "exact"} if clip["volume"] == "1" else {"kind": "relative", "value": 2.4e-7}
    else:
        span = max(abs(x) for x in fr[f0:f0 + int(len(vals) * inc / 2 ** 32) + 2]) / 32768
        tol = {"kind": "absolute", "value": 2 * ulp32(span)}
        lo = [i for i, x in enumerate(vals) if x == 0.0]
        assert not lo, ("linear output exactly 0", lo)
    wins = [{"from": start - 16, "values": [0.0] * 16, "tolerance": {"kind": "exact"}},
            {"from": start, "values": vals, "tolerance": tol}]
    if direct:
        wins.append({"from": start + len(vals), "values": [0.0] * 32, "tolerance": {"kind": "exact"}})
    info = {"samples_per_beat": clock.spb, "press_beat": ln["press_beat"], "launch_boundary_beat": ln["B"],
            "first_frame": f0, "read_step_fixed_32_32": inc, "read_step": inc / 2 ** 32,
            "gain": GAIN[clip["volume"]], "kernel": "direct copy" if direct else "linear interpolation"}
    return {"outcome": "opens", "audio": {"track": 1, "channels": "left and right", "windows": wins}}, info


# ---- package ----
TARGET = "Ableton Live 12 Suite 12.4.3 (2026-07-07_e3d8be4d07) / macOS (arm64 and x86_64 builds)"
COMPARE_MIDI = ("the set opens; the note events that track 1's session clip sends into the track's device chain "
                "with a render sample inside the window form exactly the listed sequence: same count and order, each "
                "event's render sample one of its listed samples, type, key and velocity exact")
COMPARE_AUDIO = ("the set opens; track 1's clip signal (before the track's devices and mixer) equals, on the left "
                 "and on the right channel, the listed value at every listed render sample, within the window's "
                 "tolerance; samples outside the windows are not compared")


def expected(c):
    if c["kind"] == "audio":
        return audio_expect(c["set"], c["sr"], c["script"])
    win = c["window"]
    clip = c["set"]["track"][1]
    if win is None and clip["loop_on"]:  # looped clip: window ends at song beat B + 0.9 (no event there)
        clock = clock_for(c["set"], c["sr"], c["script"])
        ln = launch_of(c["set"], clip, clock, c["script"])
        assert ln["seg"] == 0 and clock.segs[0]["b"] == 0.0
        win = m.math.ceil((ln["B"] + 0.9) * clock.spb)
    if win is None:
        exp, _ = midi_expect(c["set"], c["sr"], c["script"], 10 ** 9)
        win = max(exp["midi"]["events"][-1]["samples"]) + 100
    return midi_expect(c["set"], c["sr"], c["script"], win)


def case_record(c):
    exp, info = expected(c)
    rec = {"id": c["id"], "kind": c["kind"], "purpose": c["purpose"], "requirements": sorted(set(c["reqs"])),
           "input": f"fixtures/{c['fixture']}.als"}
    if c["kind"] == "audio":
        rec["samples"] = [f"fixtures/Samples/{c['set']['track'][1]['wav']}"]
    rec.update({"sample_rate": c["sr"], "script": c["script"], "expected": exp, "informative": info,
                "expectation_provenance": c["prov"], "stated_assumptions": sorted(c["assume"]),
                "reference_execution": "not-run", "candidate_execution": "not-run",
                "comparator": COMPARE_AUDIO if c["kind"] == "audio" else COMPARE_MIDI})
    return rec


def build():
    (FIX / "Samples").mkdir(parents=True, exist_ok=True)
    wavs = {n: write_wav(n) for n in sorted(WAVS)}
    written = {}
    for c in CASES:
        kind, clip = c["set"]["track"]
        trk = (kind, midi_clip(clip) if kind == "midi" else audio_clip(clip, wavs[clip["wav"]]))
        data = gz(live_set({**c["set"], "track": trk}))
        assert written.setdefault(c["fixture"], data) == data, ("fixture name reused for different content", c["fixture"])
    for name, data in sorted(written.items()):
        (FIX / f"{name}.als").write_bytes(data)
    cases = [case_record(c) for c in CASES]
    doc = {"schema": "playback-core-cases-v1", "target": TARGET,
           "scope": "playback-core-v1 partial requirement clauses only (see spec.md)", "status": "candidate-unreviewed",
           "fixture_origin": "Independently generated minimal Live Sets and two generated 16-bit WAV files; no shipped "
                             "file content",
           "oracle_status": "Extracted-execution arithmetic and static-derived expectations (label per case); neither "
                            "the reference application nor a candidate executed",
           "representation": {
               "input": "Live Set file (gzip); samples: WAV files it references, relative to the set's folder",
               "sample_rate": "render sample rate in Hz",
               "script": "actions in order, each handled at render sample `at`: play (start_beat), stop, continue, "
                         "launch (track, slot; transport stopped: start_beat); see spec.md",
               "midi": "window [from, to) of render samples; events: samples (one value, or two: either is "
                       "accepted), type note-on or note-off, key, velocity (binary32 value, compared after exact "
                       "widening)",
               "audio": "windows: from (first render sample) and values (one per consecutive sample, both "
                        "channels); tolerance exact, relative (|a - e| <= value * |e|) or absolute (|a - e| <= value)",
               "informative": "derived quantities shown for understanding; not compared",
               "note": "project comparison representation, not an API of the original application or a required "
                       "design"},
           "cases": cases}
    (STAGE / "cases.json").write_text(json.dumps(doc, indent=1) + "\n")
    meta = manifest_meta(len(cases))
    old = STAGE / "manifest.json"
    if old.exists():
        meta["files"] = json.loads(old.read_text()).get("files", [])
    old.write_text(json.dumps(meta, indent=1) + "\n")
    print(json.dumps({"cases": len(cases), "fixtures": len(written), "wavs": len(wavs)}))


from manifest_meta import manifest_meta  # noqa: E402  (scope, exclusions and assumptions text)

if __name__ == "__main__":
    {"build": build}[sys.argv[1]]()
