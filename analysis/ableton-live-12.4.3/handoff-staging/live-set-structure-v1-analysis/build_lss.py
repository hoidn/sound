def extra(schema, root):
    """Refusal conditions that schema_check/fixture_audit do not measure (REQ-001, 002 grouping, 016 text)."""
    out = []

    def walk(e, cls, path):
        fields = schema.get(cls)
        if fields is None:
            return
        for tag, k in Counter(c.tag for c in e if c.tag in fields).items():
            if k > 1:
                out.append(f"REQ-001: duplicate member {cls}/{tag}")
        for c in e:
            f = fields.get(c.tag)
            if f is None:
                continue
            fcls, ftype, _ = f
            if ftype == "-4" and "Value" not in c.attrib:
                out.append(f"REQ-001: value element without Value: {path}/{c.tag}")
            elif ftype == "0":
                walk(c, fcls, f"{path}/{c.tag}")
            elif ftype == "-1":
                for item in c:
                    i = item.get("Id")
                    if i is not None and not re.fullmatch(r"-?[0-9]+", i):
                        out.append(f"REQ-016: list-item Id not an integer: {path}/{c.tag}/{item.tag}")
                    walk(item, item.tag, f"{path}/{c.tag}/{item.tag}")

    walk(root.find("LiveSet"), "LiveSet", "LiveSet")
    tracks = list(root.find("LiveSet/Tracks")) if root.find("LiveSet/Tracks") is not None else []
    if not any(t.tag == "GroupTrack" for t in tracks) and any(
            t.find("TrackGroupId") is not None and t.find("TrackGroupId").get("Value") != "-1" for t in tracks):
        out.append("REQ-002: grouped track in a set without group tracks")
    return sorted(out)


def isolation(schema, data):
    """Measured refusal reasons, unknown shapes and schema deviations of one decoded fixture."""
    root = ET.fromstring(data)
    note = None
    try:
        dev, r = fa.measure(schema, root)
    except TypeError:  # rules() reads NextPointeeId/@Value as int; measure the rest with it restored
        fixed = copy.deepcopy(root)
        fixed.find("LiveSet/NextPointeeId").set("Value", "67")
        dev, r = fa.measure(schema, fixed)
        note = "checker rules() cannot read <NextPointeeId />; rules measured with Value 67 restored"
    got = {"refusals": sorted(fa.refusals(r, dev)), "unknowns": sorted(fa.unknowns(r)),
           "deviations": sorted(dev), "extra": extra(schema, root)}
    return got, note


def check_fixtures(schema, texts):
    base = texts[MIN_ALS]
    report, problems = {}, {}
    for c in lc.CASES:
        if c["action"] != "open":
            continue
        rel = MIN_ALS if c["edit"] is None else f"fixtures/{lc.cid(c['n'])}.als"
        got, note = isolation(schema, texts[rel])
        want = {k: sorted(c["check"].get(k, [])) for k in ("refusals", "unknowns", "deviations", "extra")}
        diff = [ln for ln in difflib.unified_diff(base.decode().splitlines(), texts[rel].decode().splitlines(),
                                                   lineterm="", n=0) if ln[:1] in "+-" and ln[:3] not in ("+++", "---")]
        report[lc.cid(c["n"])] = {"input": rel, "measured": got, "checker_note": note,
                                  "changed_lines_vs_T11_MIN": diff}
        if got != want:
            problems[lc.cid(c["n"])] = {"declared": want, "measured": got}
        if (c["expected"]["outcome"] == "refused") != bool(got["refusals"] or got["extra"]
                                                           or any(d.startswith("unknown-class") for d in got["deviations"])):
            problems.setdefault(lc.cid(c["n"]), {})["outcome"] = "expected outcome disagrees with measured reasons"
    return report, problems


