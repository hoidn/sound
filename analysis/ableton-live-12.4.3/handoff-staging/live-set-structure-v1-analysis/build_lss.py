def sha(b):
    return hashlib.sha256(b).hexdigest()


def gz(data):
    c = zlib.compressobj(9, zlib.DEFLATED, -15)
    return GZ_HEADER + c.compress(data) + c.flush() + struct.pack("<II", zlib.crc32(data), len(data))


def render_et(e, depth, out):
    """make_fixture.render for an ElementTree element (tabs, ' />' for childless elements)."""
    a = "".join(f' {k}="{mf.esc(x)}"' for k, x in e.attrib.items())
    pad = "\t" * depth
    if len(e):
        out.append(f"{pad}<{e.tag}{a}>")
        for k in e:
            render_et(k, depth + 1, out)
        out.append(f"{pad}</{e.tag}>")
    else:
        out.append(f"{pad}<{e.tag}{a} />")


def text(root):
    lines = ['<?xml version="1.0" encoding="UTF-8"?>']
    render_et(root, 0, lines)
    return ("\n".join(lines) + "\n").encode("utf-8")


def t11_min(sample):
    lines = ['<?xml version="1.0" encoding="UTF-8"?>']
    mf.render(mf.build(sample), 0, lines)
    return ("\n".join(lines) + "\n").encode("utf-8")


def fixture_texts(sample):
    """{published path: decoded XML} for T11-MIN and every edited variant."""
    packet = t11_min(sample)
    root = ET.fromstring(packet)
    assert text(root) == packet, "ElementTree round trip changes T11-MIN"
    lc.device_free(root)  # review narrowing: no fixture holds a device
    base = text(root)
    out = {MIN_ALS: base}
    for c in lc.CASES:
        if c["edit"] is not None:
            r = copy.deepcopy(root)
            c["edit"](r)
            data = text(r)
            assert data != base, c["n"]
            out[f"fixtures/{lc.cid(c['n'])}.als"] = data
    return out


