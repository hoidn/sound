"""Stage the live-set-structure-v1 release candidate (analyst side; not reviewed, not released).

Run from any directory with CPython 3.13 and -I:
  python3 -I build_lss.py build          # fixtures/ + cases.json + manifest.json (files[] empty)
  python3 -I build_lss.py seal           # manifest files[], author-validation.json, traceability.json
  python3 -I build_lss.py verify <dir>   # hashes, inventory, links, deny-list of an exported copy

T11-MIN is generated by r2/t11-structure-v1/make_fixture.py (imported, unchanged): its build() tree,
render() text and wav() sample. The XML must equal that packet's fixtures/T11-MIN.xml byte for byte after the review's narrowing
(lss_cases.device_free: both device lists emptied, NextPointeeId 67);
only the gzip header differs (OS byte 19, the shipped .als form graded by als-container-v1, instead of
Python's 255). Every other fixture is T11-MIN parsed, changed by one edit below and rendered with
make_fixture's layout. seal checks every fixture with the packet's checker (schema_check.check,
fixture_audit.measure/refusals/unknowns) plus extra() for the REQ-001/002/016 refusals the checker
does not measure: each refusal fixture must show exactly its tested reason and each other fixture
none. Case data and traceability are in lss_cases.py. README.md, AGENTS.md and spec.md are
hand-written.
"""
