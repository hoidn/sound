XEXEC = HERE.parents[3] / "tools/xexec"
LOADER = Path("/var/tmp/sound-analysis/xexec-t11/xexec")


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


files = {str(p.relative_to(HERE)): {"sha256": sha(p), "bytes": p.stat().st_size}
         for p in sorted(HERE.rglob("*"))
         if p.is_file() and p.name != "manifest.json" and "__pycache__" not in p.parts and not p.name.startswith(".")}
manifest = {
    "id": "T11-STRUCTURE-V1",
    "packet": "T1.1 Live Set structure: shipped schema, shipped documents and static reading of the reader",
    "target": "Ableton Live 12 Suite 12.4.3 (arm64 release slice; x86_64 slice for disassembly checks)",
    "inputs": {"schema 12.0_12402.txt": sha(SCHEMA), "Live.arm64": sha(ARM64), "Live_x86_64": sha(X86),
               "documents": "out/inputs-documents.tsv (SHA-256 of each shipped .als/.alc read)",
               "corpora": ["/var/tmp/sound-analysis/corpus (arm64 C1/C2)", "/var/tmp/sound-analysis/corpus-x86"]},
    "tools": {"python": platform.python_version(), "objdump": "GNU objdump (GNU Binutils for Ubuntu) 2.42",
              "gcc": "gcc (Ubuntu 13.3.0-6ubuntu2~24.04.1) 13.3.0", "glibc": platform.libc_ver()[1]},
    "commands": ["sh run.sh"],
    "executed_live_application": False,
    "executed_original_code": "x86_64 0x101191310 only (CRC step; x-crc/x_crc.py, results out/x-crc.json), "
                              "in the unchanged tools/xexec harness on Linux x86_64",
    "harness": {"tools/xexec/xexec.py": sha(XEXEC / "xexec.py"), "tools/xexec/xexec.c": sha(XEXEC / "xexec.c"),
                "built_loader": {"path": str(LOADER), "sha256": sha(LOADER)}},
    "fixture_provenance": "fixtures/ is generated by make_fixture.py from invented values; it contains no shipped bytes",
    "files": files,
}
(HERE / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
print(f"manifest.json: {len(files)} files")
