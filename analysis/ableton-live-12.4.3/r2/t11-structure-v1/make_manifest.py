"""Write manifest.json: SHA-256 and size of every evidence file, plus inputs and tool versions."""
import hashlib, json, platform
from pathlib import Path

HERE = Path(__file__).resolve().parent
BUNDLE = Path("/home/ollie/Ableton Live 12 Suite.app/Contents")
SCHEMA = BUNDLE / "App-Resources/Schema/12.0_12402.txt"
ARM64 = HERE.parents[1] / "derived/Live.arm64"
